// Questionnaire guidé (français) : ajouter une LOI au catalogue particules, sans coder.
// Double-cliquez add-element.bat ou lancez : node scripts/add-element.mjs
// Génère le module + l'enregistre dans le pack + rappelle la suite.
import * as readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lawsDir = join(root, "engines/particles/laws");
const indexFile = join(root, "engines/particles/index.js");

const TEMPLATES = {
  force: "Adds an acceleration to each targeted particle (like gravitation).",
  steering: "Eases each targeted particle velocity toward a computed vector (like pursuit).",
  interaction: "Acts on pairs of groups once per step (like predation).",
  init: "Places particles at spawn only (like circular placement).",
};

function slug(s) {
  return s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function constName(id) {
  return id.split("-").map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join("");
}

// Pure + exported for testing: build the law module source from answers.
export function buildLawSource({ id, label, formule, sources, limites, kind, params }) {
  const body =
    kind === "init"
      ? `  // Return true when it claimed the particle (custom placement).
  place(world, p, def) {
    // TODO: set p.x, p.y, p.vx, p.vy from def + world (see placement-circulaire.js).
    return false;
  },`
      : `  apply(world, dt, params, targets) {
    for (const p of world.particles) {
      if (!targets.includes(p.e)) continue;
      // TODO: modify p.ax/p.ay or world.steer(p, dx, dy, rate, dt).
      // See gravitation.js (force), poursuite.js (steering), predation.js (interaction).
    }
  },`;
  return `// Law: ${id} — generated by scripts/add-element.mjs (finish the TODO below).
export const ${constName(id)} = {
  id: "${id}",
  notice: {
    label: ${JSON.stringify(label)},
    formule: ${JSON.stringify(formule)},
    sources: ${JSON.stringify(sources)},
    limites: ${JSON.stringify(limites)},
  },
  defaults: ${JSON.stringify(params)},
${body}
};
`;
}

// Pure + exported for testing: register the law in the pack index source.
export function registerLaw(indexSrc, id) {
  const lastImport = 'import { reproduction } from "./laws/reproduction.js";';
  if (!indexSrc.includes(lastImport)) throw new Error("pack index anchor not found (imports)");
  let out = indexSrc.replace(lastImport, `${lastImport}\nimport { ${constName(id)} } from "./laws/${id}.js";`);
  const anchor = "  reproduction,\n};";
  if (!out.includes(anchor)) throw new Error("pack index anchor not found (map)");
  const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : `"${id}"`;
  const entry = key === constName(id) ? `  ${key},\n};` : `  ${key}: ${constName(id)},\n};`;
  return out.replace(anchor, `  reproduction,\n${entry}`);
}

async function main() {
  const rl = readline.createInterface({ input, output });
  const ask = (q) => rl.question(q);
  try {
    console.log("\n== AuraLab — ajouter une loi au catalogue ==\n");
    const idRaw = await ask("Nom court de la loi (ex : vent-solaire) ? ");
    const id = slug(idRaw || "");
    if (!id) {
      console.log("Abandon : nom vide.");
      return;
    }
    const file = join(lawsDir, `${id}.js`);
    if (existsSync(file)) {
      console.log(`Abandon : ${id}.js existe déjà.`);
      return;
    }
    const label = (await ask("Titre affiché (ex : Vent solaire) ? ")) || id;
    const formule = (await ask("Formule / règle en une phrase ? ")) || "À documenter.";
    const sources = (await ask("Sources (science établie ou règle inventée ?) ? ")) || "Ad-hoc.";
    const limites = (await ask("Limites (ce que la loi ne modélise PAS) ? ")) || "À documenter.";
    console.log("\nGabarits : force | steering | interaction | init");
    Object.keys(TEMPLATES).forEach((k) => console.log(`  - ${k} : ${TEMPLATES[k]}`));
    let kind = (await ask("Gabarit ? ")).trim().toLowerCase();
    if (!TEMPLATES[kind]) kind = "force";
    const paramsRaw = (await ask("Paramètres (ex : gain=1.5, portee=200 — vide si aucun) ? ")).trim();
    const params = {};
    if (paramsRaw) {
      paramsRaw.split(",").forEach((pair) => {
        const [k, v] = pair.split("=").map((s) => s.trim());
        if (!k) return;
        const n = Number(v);
        params[k] = Number.isFinite(n) && v !== "" ? n : v;
      });
    }

    writeFileSync(file, buildLawSource({ id, label, formule, sources, limites, kind, params }));
    writeFileSync(indexFile, registerLaw(readFileSync(indexFile, "utf8"), id));

    console.log(`\nOK : loi créée → engines/particles/laws/${id}.js (enregistrée dans le pack).`);
    console.log("Suite : 1) finir le TODO dans le fichier (aide : CREER-UN-LABO.md),");
    console.log("        2) node scripts/validate-config.mjs,");
    console.log(`        3) ajouter { "law": "${id}" } aux lois d'un labo pour l'utiliser.`);
  } finally {
    rl.close();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(`ERREUR : ${err.message}`);
    process.exit(1);
  });
}
